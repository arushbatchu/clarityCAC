"""
codegen.py
----------
Python is the single source of truth for Clarity's rules.

This script writes two files from the Python engine:

  frontend/src/rules.generated.ts   every signal, weight, scenario, threshold
                                    and copy string, as typed TypeScript
  shared/parity_cases.json          ~90 inputs plus the exact output the Python
                                    engine gives for each one. The TypeScript
                                    test suite must reproduce every one.

Run from the repo root:   python backend/scripts/codegen.py
CI runs it and fails if the committed files are out of date.
"""

from __future__ import annotations

import json
import sys
from dataclasses import asdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

from clarity.signals import ALL_SIGNALS, IMPLIED_BY, PHRASES, SUDDEN_ONSET  # noqa: E402
from clarity.scenarios import SCENARIOS, SYMPTOM_CHIPS           # noqa: E402
from clarity.care_locations import CARE_BY_TIER                   # noqa: E402
from clarity.engine import (                                      # noqa: E402
    TIER_CONFIG, SEVERITY_BONUS, HIGH_THRESHOLD, MODERATE_THRESHOLD,
    ENDINGS, ESCALATION_REASONS, NEGATIONS, SEVERITY_WORDS, StructuredInput, evaluate,
)


def js(value) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2)


def build_rules_ts() -> str:
    signals = [
        {"label": s.label, "weight": s.weight, "category": s.category,
         "keywords": list(s.keywords)}
        for s in ALL_SIGNALS
    ]
    scenarios = [
        {"id": s.id, "category": s.category, "label": s.label,
         "defaultSeverity": s.default_severity, "defaultOnset": s.default_onset,
         "defaultSymptoms": list(s.default_symptoms), "narrative": s.narrative}
        for s in SCENARIOS
    ]
    care = {
        tier: [{"name": p.name, "kind": p.kind, "distanceMi": p.distance_mi,
                "isOpen": p.is_open} for p in places]
        for tier, places in CARE_BY_TIER.items()
    }
    copy = {
        tier: {"headline": c["headline"], "action": c["action"],
               "whatToDo": c["what_to_do"], "watchFor": c["watch_for"]}
        for tier, c in TIER_CONFIG.items()
    }
    return f"""// AUTO-GENERATED by backend/scripts/codegen.py from the Python engine.
// Do not edit by hand. Change the Python files, then rerun codegen.

import type {{ CarePlace, RuleId, Scenario, SignalDef, Tier, TierCopy }} from "./types.js";

export const SIGNALS: readonly SignalDef[] = {js(signals)};

export const SCENARIOS: readonly Scenario[] = {js(scenarios)};

export const SYMPTOM_CHIPS: readonly string[] = {js(SYMPTOM_CHIPS)};

export const CARE: Record<Tier, readonly CarePlace[]> = {js(care)};

export const TIER_COPY: Record<Tier, TierCopy> = {js(copy)};

export const ESCALATION_REASONS: Record<RuleId, string> = {js(ESCALATION_REASONS)};

export const SEVERITY_BONUS: Record<number, number> = {js({str(k): v for k, v in SEVERITY_BONUS.items()})};

export const HIGH_THRESHOLD = {HIGH_THRESHOLD};
export const MODERATE_THRESHOLD = {MODERATE_THRESHOLD};
export const NEGATIONS: readonly string[] = {js(list(NEGATIONS))};

export const PHRASES: Record<string, string> = {js(PHRASES)};

export const IMPLIED_BY: Record<string, string> = {js(IMPLIED_BY)};

export const ENDINGS: Record<Tier, string> = {js(ENDINGS)};

export const SUDDEN_ONSET = {js(SUDDEN_ONSET)};

export const SEVERITY_WORDS: Record<number, string> = {js({str(k): v for k, v in SEVERITY_WORDS.items()})};
"""


def parity_inputs() -> list[StructuredInput]:
    cases: list[StructuredInput] = []
    # Every scenario at every severity and onset
    for sc in SCENARIOS:
        for sev in range(1, 6):
            for onset in ("sudden", "gradual"):
                cases.append(StructuredInput(sc.id, sev, onset, list(sc.default_symptoms)))
    # Chips only, no scenario
    chip_sets = [[], ["dizzy"], ["nausea", "tired"], ["face drooping"],
                 ["severe bleeding"], ["mild bleeding", "bruising"],
                 ["high fever", "chills"], ["heart feels weird"]]
    for chips in chip_sets:
        for sev in (1, 3, 5):
            cases.append(StructuredInput(None, sev, "gradual", chips))
    # Free text, including the tricky ones
    texts = [
        "not sure, something feels weird",
        "my chest pressure is mild and improving",
        "no chest pain",
        "the pain is not going away",
        "acute cut on my finger, minor",
        "my 2-year-old has a fever and is a little fussy",
        "grandmother fell and seems confused",
        "I'm pregnant and have a bad headache",
        "mild rash, getting better",
        "throat closing after eating peanuts",
        "I want to die",
        "feels odd but it passed quickly",
    ]
    for t in texts:
        for sev in (2, 4):
            cases.append(StructuredInput(None, sev, "gradual", [], t))
    return cases


def build_parity_json() -> str:
    out = []
    for inp in parity_inputs():
        r = evaluate(inp)
        out.append({
            "input": {"scenarioId": inp.scenario_id, "severity": inp.severity,
                      "onset": inp.onset, "symptoms": inp.symptoms,
                      "freeText": inp.free_text},
            "expected": {"tier": r.tier, "score": r.score, "escalated": r.escalated,
                         "escalationRule": r.escalation_rule,
                         "explanation": r.explanation,
                         "detected": [d.label for d in r.detected]},
        })
    return json.dumps(out, ensure_ascii=False, indent=1) + "\n"


def main() -> None:
    (ROOT / "frontend/src/rules.generated.ts").write_text(build_rules_ts(), encoding="utf-8")
    (ROOT / "shared").mkdir(exist_ok=True)
    (ROOT / "shared/parity_cases.json").write_text(build_parity_json(), encoding="utf-8")
    print("wrote frontend/src/rules.generated.ts and shared/parity_cases.json")


if __name__ == "__main__":
    main()
